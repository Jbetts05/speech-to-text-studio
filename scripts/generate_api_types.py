"""Generate TypeScript directly from the backend serialization schemas."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from ai_bench.api import CreateRunRequest
from ai_bench.api_contracts import (
    BenchmarkCatalogEntry,
    CreateRunResponse,
    CreateUploadRequest,
    DatasetPageResponse,
    DatasetSummaryResponse,
    FinalizedEvaluationResponse,
    LiveDetailRequiredResponse,
    RunDetailResponse,
    RunSummaryResponse,
    RuntimeResponse,
    UploadSessionResponse,
)
from ai_bench.contracts import RunEvent, RunReport
from benchmark_packs.speech_to_text.evaluation import TranscriptComparison

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "frontend" / "src" / "api" / "contracts.generated.ts"


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return "Backend" + str(schema["$ref"]).rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(_type(item) for item in schema.get("anyOf", schema.get("oneOf", [])))
    kind = schema.get("type")
    if kind == "object" or "properties" in schema:
        if "properties" not in schema:
            additional = schema.get("additionalProperties")
            value_type = _type(additional) if isinstance(additional, dict) else "unknown"
            return f"Record<string, {value_type}>"
        required = set(schema.get("required", []))
        fields = [
            f"  {json.dumps(name)}{'' if name in required else '?'}: {_type(value)};"
            for name, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_type(item) for item in schema["prefixItems"]) + "]"
        return f"({_type(schema.get('items', {}))})[]"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def generated_types() -> str:
    schema = TypeAdapter(
        BenchmarkCatalogEntry
        | CreateRunResponse
        | CreateRunRequest
        | CreateUploadRequest
        | RunDetailResponse
        | FinalizedEvaluationResponse
        | LiveDetailRequiredResponse
        | RunSummaryResponse
        | DatasetPageResponse
        | DatasetSummaryResponse
        | RuntimeResponse
        | UploadSessionResponse
        | RunEvent
        | RunReport
        | TranscriptComparison
    ).json_schema(mode="serialization")
    declarations = [
        f"export type Backend{name} = {_type(value)};"
        for name, value in sorted(schema["$defs"].items())
    ]
    return (
        "// Generated by scripts/generate_api_types.py. Do not edit by hand.\n\n"
        + "\n\n".join(declarations)
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    expected = generated_types()
    if arguments.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
            raise ValueError(
                "Frontend API types drifted; run python scripts/generate_api_types.py."
            )
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
